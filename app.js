function showResult(value, crop, source, inputs, note, isApi){
 $('result-placeholder').hidden=true; $('result-error').hidden=true; $('result-content').hidden=false;
 $('yield-value').textContent=Number(value).toFixed(2); $('result-crop').textContent=crop;
 $('result-source').textContent=source; $('result-inputs').textContent=inputs; $('result-note').textContent=note;
 $('result-badge').textContent=isApi?'API MODEL':'DEMO'; $('api-status').textContent=isApi?'Connected to model API':'Simulated demo output · not validated';
 $('model-status').textContent=isApi?'API connected':'Demo formula'; $('model-sub').textContent=isApi?'Prediction returned by API':'No real model API connected';
}
function demoEstimate(crop,rain,temp,ph,irrigation){
 // UI-only illustrative estimate, intentionally not represented as a scientifically trained model.
 const base={Wheat:2.7,Rice:3.2,Maize:4.1,Cotton:1.6,Sugarcane:65,Pulses:0.9}[crop]||2;
 const rainFactor=Math.max(.35,1-Math.abs(rain-(crop==='Rice'?1200:crop==='Sugarcane'?1400:650))/(crop==='Rice'?2200:crop==='Sugarcane'?2600:1400)*.5);
 const tempFactor=Math.max(.45,1-Math.abs(temp-(crop==='Wheat'?22:28))/50);
 const phFactor=Math.max(.65,1-Math.abs(ph-6.5)*.08);
 return Math.max(.05,base*rainFactor*tempFactor*phFactor*(irrigation?1.05:.88));
}
$('prediction-form').addEventListener('submit',async e=>{
 e.preventDefault();
 const crop=$('crop').value, rainfall=Number($('rainfall').value), temperature=Number($('temperature').value), soil_ph=Number($('soilph').value), irrigation=Number($('irrigation').value);
 if(!Number.isFinite(rainfall)||!Number.isFinite(temperature)||!Number.isFinite(soil_ph)){toast('Please enter valid numeric values.');return;}
 const api=$('api-url').value.trim().replace(/\/+$/,'');
 const inputs=`${rainfall} mm rain · ${temperature}°C · pH ${soil_ph} · irrigation ${irrigation?'yes':'no'}`;
 $('result-placeholder').hidden=true; $('result-content').hidden=true; $('result-error').hidden=true;
 $('api-status').textContent='Running prediction…';
 if(api){
   try{
    const res=await fetch(api+'/predict',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({crop,rainfall_mm:rainfall,temperature_c:temperature,soil_ph,irrigation})});
    if(!res.ok) throw new Error(`API returned HTTP ${res.status}. Check the API deployment and URL.`);
    const data=await res.json();
    showResult(data.predicted_yield_tonnes_per_hectare,crop,data.model_source||'Trained model',inputs,data.warning||'This is a model estimate, not a guarantee of actual harvest.',true);
   }catch(err){
    $('result-error').hidden=false; $('result-error').textContent=`Could not reach the API: ${err.message} Check that the API is online, the URL is correct, and CORS allows this Netlify site. Demo output is not shown as a fallback so API failures remain visible.`; $('api-status').textContent='API connection failed';
   }
 }else{
   const y=demoEstimate(crop,rainfall,temperature,soil_ph,irrigation);
   showResult(y,crop,'Illustrative demo formula',inputs,'This value is generated by a simple illustrative formula—not a trained or validated agricultural model. Replace demo mode with a model trained and tested on real yield records before using or presenting it as a real prediction.',false);
 }
});

// Optional API diagnostics: displays model readiness and measured metrics when an API URL is supplied.
async function checkApiInfo(){
 const api=$('api-url').value.trim().replace(/\/+$/,'');
 if(!api) return;
 try {
  const r=await fetch(api+'/model-info'); if(!r.ok) return; const info=await r.json();
  if(info.model_available){ $('model-status').textContent='Trained API model'; $('model-sub').textContent=info.model_source || 'Model available'; }
  const mr=await fetch(api+'/metrics'); if(mr.ok){ const m=await mr.json(); $('metrics-status').textContent='MAE '+m.mae; $('metrics-status').title='RMSE: '+m.rmse+' | R²: '+m.r2+' | '+(m.dataset_note||''); }
 } catch(e) { /* do not interrupt the form; connection errors appear on prediction */ }
}
$('api-url').addEventListener('change',checkApiInfo);
